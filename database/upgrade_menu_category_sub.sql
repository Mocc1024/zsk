-- =============================================================
--  「分类管理」归入「内容管理」二级菜单（M2.7）
--
--  背景：分类与回收站、标签一样都是内容的属性维度，原先却挂在一级菜单，
--        导致内容相关的入口分散在两处。按使用习惯调整为内容管理的子级。
--
--  做法：把 zsk_auth_rule 的 #30「分类管理」pid 由 0 改为 20（内容管理），
--        并把 sort 降到 28，排在「内容列表 / 内容回收站 / 标签管理」之后。
--
--  权限影响：#30 下仍有 category.list 等权限点（type=2），
--            已有用户组的授权不受影响；菜单树靠「后代权限点是否被授权」
--            决定是否保留，因此分类管理菜单对内容运营 / 只读访客组依然可见。
--
--  幂等：定值 UPDATE，可重复执行
-- =============================================================

SET NAMES utf8mb4;

UPDATE `zsk_auth_rule`
SET `pid`         = 20,
    `sort`        = 28,
    `update_time` = NOW()
WHERE `id` = 30;

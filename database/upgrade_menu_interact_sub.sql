-- =============================================================
--  「互动管理」归入「内容管理」二级菜单
--
--  背景：评论审核、举报处理、敏感词、积分规则等都是围绕内容产生的
--        互动行为，按使用习惯归入内容管理子级，与
--        内容列表 / 内容回收站 / 标签管理 / 分类管理 同级。
--        （先例：upgrade_menu_category_sub.sql 把分类管理挪入 #20）
--
--  做法：zsk_auth_rule 的 #120「互动管理」pid 由 0 改为 20（内容管理），
--        sort 降为 27，排在「内容列表 / 回收站 / 标签 / 分类」之后。
--
--  权限影响：#120 的子权限点（#121-128，comment.* / report.* / level.* /
--            points.* 等）保持 pid=120 不动，已有用户组的授权不受影响；
--            菜单树靠「后代权限点是否被授权」决定保留，超管组 rules='*' 不受影响。
--
--  幂等：定值 UPDATE，可重复执行
-- =============================================================

SET NAMES utf8mb4;

UPDATE `zsk_auth_rule`
SET `pid`         = 20,
    `sort`        = 27,
    `update_time` = NOW()
WHERE `id` = 120;

-- 校验：应返回 pid=20 / sort=27
SELECT `id`, `pid`, `sort`, `title`, `path`
FROM `zsk_auth_rule`
WHERE `id` = 120;
